// Seed with `cargo run -p ose-server --example part_controls_fixture -- 127.0.0.1:7797`.
import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const base=process.env.OSE_BASE_URL??'http://127.0.0.1:7797';
if(!/^http:\/\/(127\.0\.0\.1|localhost):/.test(base)) throw new Error('Use a disposable local server');
const out=path.join(root,'.cache/part-controls');
await fs.mkdir(out,{recursive:true});
const fixture=JSON.parse(await fs.readFile(path.join(out,'fixture.json'),'utf8'));
const browser=await chromium.launch({channel:'chromium',headless:true,args:['--enable-unsafe-webgpu','--ignore-gpu-blocklist','--disable-dawn-features=use_dxc']});
const page=await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[];
page.setDefaultTimeout(30000);
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error') errors.push(m.text());});
await page.addInitScript(token=>{
  localStorage.setItem('ose.token',token);
  localStorage.setItem('ose.hints','off');
  window.partControlSounds=[];
  new MutationObserver(records=>{
    for(const r of records) if(r.attributeName==='data-ose-sfx-started') window.partControlSounds.push({sound:r.target.getAttribute(r.attributeName),time:performance.now()});
  }).observe(document,{subtree:true,attributes:true,attributeFilter:['data-ose-sfx-started']});
},fixture.token);
const hud=page.locator('[data-ose=flight].open');
const state=async()=>JSON.parse(await hud.getAttribute('data-ose-part-controls'));
const shot=async name=>page.screenshot({path:path.join(out,`${name}.png`)});
const waitState=async(index,part,out)=>page.waitForFunction(({index,part,out})=>{
  const raw=document.querySelector('[data-ose=flight]')?.getAttribute('data-ose-part-controls');
  return raw&&JSON.parse(raw)[index].some(([i,v])=>i===part&&v===out);
},{index,part,out});
const expectCue=async name=>page.waitForFunction(name=>window.partControlSounds.some(e=>e.sound===name),name);
try {
  await page.goto(base);
  await page.locator('[data-ose=player-name]').fill('Part control audit');
  await page.locator('[data-ose=play]').click();
  await page.locator(`[data-ose="session-join"][data-ose-session="${fixture.campaign}"]`).click();
  await page.locator('[data-ose=ksc-launchpad]').waitFor();
  const hints=page.getByText('No more hints',{exact:true});
  if(await hints.isVisible()) await hints.click();
  await page.locator('[data-ose=ksc-launchpad]').click();
  await page.locator('[data-ose=craft]').filter({hasText:'Part controls audit'}).locator('.name').click();
  await page.locator('[data-ose=lp-orbit]').click();
  await hud.waitFor();
  await page.waitForTimeout(5000);
  assert.equal(await page.locator('[data-ose=gpu]').getAttribute('data-ose-renderer'),'webgpu');
  await page.mouse.move(800,450);
  await page.mouse.wheel(0,-750);
  await page.waitForTimeout(500);
  const initial=await state();
  await shot('closed');
  await page.locator('#fh-act-lights').click();
  await waitState(3,6,true);
  await expectCue('light_on');
  await shot('lights-on');
  await page.keyboard.press('u');
  await waitState(3,6,false);
  await expectCue('light_off');
  await page.locator('#fh-act-antennas').click();
  await waitState(2,3,true);
  await page.waitForTimeout(550);
  await shot('antenna-moving');
  await expectCue('Play_An_Antenna_Dish_16_open_rise_last');
  await shot('antenna-open');
  await page.locator('#fh-act-antennas').click();
  await waitState(2,3,false);
  await expectCue('Play_An_Antenna_Dish_16_close_last');
  await page.locator('#fh-act-solar').click();
  await waitState(1,4,true);
  await waitState(1,5,true);
  await page.waitForTimeout(1000);
  await shot('panels-moving');
  await expectCue('Play_An_SolarArray_1x6_Shielded_open_5');
  await shot('panels-open');
  await page.locator('#fh-act-solar').click();
  await waitState(1,4,false);
  await waitState(1,5,true); // OX-4L stays extended.
  await expectCue('Play_An_SolarArray_1x6_Shielded_close_5');
  await page.locator('#fh-act-solar').click(); // One-shot panel must not prevent reopening the reversible one.
  await waitState(1,4,true);
  const outGear=!initial[0][0][1];
  await page.locator('#fh-act-gear').click();
  await waitState(0,2,outGear);
  await page.waitForTimeout(700);
  await shot('leg-moving');
  await expectCue(`Play_An_Landing_Leg_Tiny_Extensible_LT_05_${outGear?'deploy':'retract'}_4`);
  await shot('leg-terminal');
  await page.keyboard.press('g');
  await waitState(0,2,!outGear);
  await expectCue(`Play_An_Landing_Leg_Tiny_Extensible_LT_05_${!outGear?'deploy':'retract'}_4`);
  await page.locator('#fh-act-antennas').click();
  await page.waitForTimeout(500);
  await page.locator('#fh-act-antennas').click(); // Reverse midway, then settle.
  await waitState(2,3,false);
  await page.waitForTimeout(2500);
  const saved=await state();
  await page.keyboard.press('F5');
  await page.getByText('Quicksave done',{exact:false}).waitFor();
  await page.locator('#fh-act-lights').click();
  await waitState(3,6,true);
  await page.locator('#fh-act-antennas').click();
  await waitState(2,3,true);
  await page.keyboard.press('F9');
  await page.getByText('Quickload done',{exact:false}).waitFor();
  await waitState(2,3,false);
  await waitState(3,6,false);
  assert.deepEqual(await state(),saved);
  const cuesAfterLoad=await page.evaluate(()=>window.partControlSounds.length);
  await page.waitForTimeout(300);
  const replayed=await page.evaluate(n=>window.partControlSounds.slice(n).filter(e=>e.sound.startsWith('Play_An_')||e.sound==='light_off'),cuesAfterLoad);
  assert.deepEqual(replayed,[], 'loading saved terminal states must not replay deployment sounds');
  await shot('restored');
  assert.deepEqual(errors,[]);
  await fs.writeFile(path.join(out,'browser-results.json'),JSON.stringify({initial,final:await state(),sounds:await page.evaluate(()=>window.partControlSounds),errors},null,2));
  console.log('PASS: lights button/U, antenna extend/retract/reverse, solar permissions/mixed groups, gear button/G, F5/F9 restore; actual Web Audio starts; WebGPU without browser errors');
} catch(e) {
  await shot('failure');
  await fs.writeFile(path.join(out,'failure.txt'),`${e.stack}\nControls: ${await page.locator("[data-ose=flight]").getAttribute("data-ose-part-controls")}\nSounds: ${JSON.stringify(await page.evaluate(()=>window.partControlSounds))}\n${await page.locator('body').innerText()}\n${JSON.stringify(errors)}`);
  throw e;
} finally {await browser.close();}
