// Local visual regression: hatch hold -> release -> grab -> jetpack -> board.
import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const base = process.env.OSE_BASE_URL || 'http://127.0.0.1:7799';
if (!/^http:\/\/(127\.0\.0\.1|localhost):/.test(base)) throw new Error('Use a local test server');
const out = new URL('../../.cache/eva-parity/', import.meta.url);
await fs.mkdir(out, {recursive:true});
const browser = await chromium.launch({channel:'chromium',headless:true,args:['--enable-unsafe-webgpu','--ignore-gpu-blocklist','--disable-dawn-features=use_dxc']});
const page = await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[];
page.setDefaultTimeout(30_000);
page.on('pageerror', e=>errors.push(e.message));
try {
  await page.goto(base);
  await page.locator('[data-ose="player-name"]').fill('EVA comparison '+Date.now());
  await page.locator('[data-ose="login"]').click();
  await page.locator('[data-ose="play"]').click();
  await page.locator('[data-ose="session-join"]').first().waitFor();
  if (!await page.locator('#create-name').isVisible()) await page.locator('#create-details > summary').click();
  await page.selectOption('#create-mode','Sandbox');
  await page.fill('#create-name','EVA space comparison '+Date.now());
  await page.locator('[data-ose="create"]').click();
  await page.locator('[data-ose="ksc-launchpad"]').waitFor({state:'visible'});
  const hints=page.getByText('No more hints', {exact:true});
  if (await hints.isVisible()) await hints.click();
  await page.locator('[data-ose="ksc-launchpad"]').click();
  const row=page.locator('[data-ose="craft"]').filter({hasText:'Stock12_StartRocket'}).first();
  await row.locator('.name').click();
  await page.locator('[data-ose="lp-orbit"]').click();
  const hud=page.locator('[data-ose="flight"].open');
  await hud.waitFor();
  await page.waitForTimeout(5000);
  assert.equal(await page.locator('[data-ose="gpu"]').getAttribute('data-ose-renderer'), 'webgpu');
  const pod=await hud.getAttribute('data-ose-vessel');
  await page.locator('[data-ose="flight-eva"]').click();
  await page.waitForFunction(()=>document.querySelector('[data-ose="flight"]')?.getAttribute('data-ose-eva-attached')==='true');
  const jeb=await hud.getAttribute('data-ose-vessel');
  assert.notEqual(jeb,pod);
  await page.waitForTimeout(4000);
  await page.screenshot({path:new URL('ose-space-exit.png',out).pathname.replace(/^\/([A-Za-z]:)/,'$1')});
  await page.keyboard.press('f');
  await page.waitForFunction(()=>document.querySelector('[data-ose="flight"]')?.getAttribute('data-ose-eva-attached')==='false');
  await page.keyboard.press('f');
  await page.waitForFunction(()=>document.querySelector('[data-ose="flight"]')?.getAttribute('data-ose-eva-attached')==='true');
  await page.keyboard.press('Space');
  await page.waitForFunction(()=>document.querySelector('[data-ose="flight"]')?.getAttribute('data-ose-eva-attached')==='false');
  await page.screenshot({path:new URL('ose-space-release.png',out).pathname.replace(/^\/([A-Za-z]:)/,'$1')});
  await page.keyboard.press('r');
  await page.keyboard.down('w');
  await page.waitForTimeout(150);
  await page.keyboard.up('w');
  await page.keyboard.press('r');
  await page.keyboard.press('b');
  await page.waitForFunction(id=>document.querySelector('[data-ose="flight"]')?.getAttribute('data-ose-vessel')===id,pod);
  assert.deepEqual(errors,[]);
  console.log('PASS: orbit EVA holds, F releases/grabs, Space releases, R toggles jetpack, B boards; no browser errors');
} catch(e) {
  await page.screenshot({path:new URL('failure.png',out).pathname.replace(/^\/([A-Za-z]:)/,'$1')});
  console.error(await page.locator('body').innerText());
  throw e;
} finally {await browser.close();}
