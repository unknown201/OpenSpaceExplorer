import { expect, test } from "@playwright/test";

test("map navball follows steering and SAS can be switched off", async ({ page, baseURL }) => {
  page.setDefaultTimeout(10_000);
  await page.goto(baseURL!);
  await page.locator('[data-ose="player-name"]').fill("attitude pilot");
  await page.locator('[data-ose="play"]').click();
  await page.locator('[data-ose="session-join"]').first().click();
  await page.locator('[data-ose="ksc-launchpad"]').click();
  await page.locator('[data-ose="craft"]').filter({ hasText: "Stock12_StartRocket" }).click();
  await page.locator('[data-ose="lp-orbit"]').click();
  await page.locator('[data-ose="ksc-button"]').click();
  await page.locator('[data-ose="ksc-tracking"]').click();
  await page.locator('[data-ose="ts-vessel"].mine').filter({ hasText: 'Stock12_StartRocket' }).last().click();
  await page.locator('[data-ose="ts-fly"]').click();
  const sas = page.locator('#fh-sas-toggle');
  const ball = page.locator('[data-ose="flight-navball"]');
  await expect(ball).toHaveAttribute('data-ose-navball', 'drawn');
  await sas.click();
  await expect(sas).not.toHaveClass(/on/);
  await expect(page.locator('#fh-attitude')).toHaveText('SAS off');
  await page.keyboard.press('t');
  await expect(sas).toHaveClass(/on/);
  await page.keyboard.press('m');
  await expect(page.locator('[data-ose="flight"]')).toHaveClass(/map/);
  const initial = await ball.getAttribute('data-ose-forward');
  await page.keyboard.down('w');
  await expect.poll(() => ball.getAttribute('data-ose-forward')).not.toBe(initial);
  await page.waitForTimeout(800);
  await page.keyboard.up('w');
  await page.waitForTimeout(2000);
  const settled = (await ball.getAttribute('data-ose-forward'))!.split(',').map(Number);
  await page.waitForTimeout(12_000);
  const after = (await ball.getAttribute('data-ose-forward'))!.split(',').map(Number);
  expect(after.reduce((sum, v, i) => sum + v * settled[i], 0)).toBeGreaterThan(0.999);
  const before = await ball.getAttribute('data-ose-forward');
  await page.keyboard.down('d');
  await expect.poll(() => ball.getAttribute('data-ose-forward')).not.toBe(before);
  await page.keyboard.up('d');
});
